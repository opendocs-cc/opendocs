const PERMISSION: Record<string, string> = {
  "docs:read": "Read",
  "docs:write": "Create and change",
  integrations: "Drive and e-signatures",
  "workspace:admin": "Team and workspace admin",
};

function firstSentence(text: string): string {
  const match = /^(.+?[.!?])(\s|$)/s.exec(text);
  return (match ? match[1] : text)
    .replace(/\n/g, " ")
    // Markdown in descriptions (an example image tag) is shown as code, and
    // MDX-sensitive characters are escaped so the docs build accepts it.
    .replace(/!\[[^\]]*\]\([^)]*\)/g, (m) => `\`${m}\``)
    .replace(/[<{}]/g, (c) => `\\${c}`)
    .replace(/\|/g, "\\|");
}

function behaviour(tool: AnyTool): string {
  if (tool.annotations.readOnlyHint) return "Read only";
  if (tool.annotations.destructiveHint) return "Asks you first";
  if (tool.annotations.openWorldHint) return "Visible to others";
  return "Changes your data";
}

function params(tool: AnyTool): string {
  const shape = (tool.input as z.ZodObject).shape as Record<string, z.ZodType>;
  const names = Object.keys(shape);
  return names.length === 0 ? "none" : names.map((n) => `\`${n}\``).join(", ");
}

const byName = new Map(TOOLS.map((t) => [t.name, t]));
const listed = new Set(GROUPS.flatMap((g) => g.names));
const unlisted = TOOLS.filter((t) => !listed.has(t.name)).map((t) => t.name);
if (unlisted.length > 0) {
  console.error(`Add these tools to a group in gen-tool-docs.ts: ${unlisted.join(", ")}`);
  process.exit(1);
}

const lines: string[] = [
  "---",
  "title: MCP tools reference",
  "description: Every tool the OpenDocs MCP server offers to Claude, ChatGPT and other AI apps.",
  "---",
  "",
  "<!-- Generated by apps/mcp/scripts/gen-tool-docs.ts from the tool definitions. Don't edit by hand. -->",
  "",
  "# MCP tools reference",
  "",
  `The OpenDocs MCP server (\`https://mcp.opendocs.cc/mcp\`) offers ${TOOLS.length} tools. An app only sees the tools for the permissions you approved when you connected it. You don't call these yourself: you ask in plain words and the app picks the tool. See [Connect OpenDocs over MCP](../integrations/mcp.md) to set it up.`,
  "",
  "**Behaviour:** *Read only* tools never change anything. *Asks you first* tools change or remove things; apps like Claude ask before running them, and OpenDocs also requires an explicit confirmation for deleting, going public and sending for signature. *Visible to others* tools publish, share or email.",
  "",
];

for (const group of GROUPS) {
  lines.push(`## ${group.title}`, "", group.intro, "", "| Tool | What it does | Permission | Behaviour | Parameters |", "|---|---|---|---|---|");
  for (const name of group.names) {
    const tool = byName.get(name);
    if (!tool) {
      console.error(`Unknown tool in gen-tool-docs.ts: ${name}`);
      process.exit(1);
    }
    lines.push(
      `| \`${tool.name}\` | ${firstSentence(tool.description)} | ${PERMISSION[tool.scope]} | ${behaviour(tool)} | ${params(tool)} |`,
    );
  }
  lines.push("");
}

writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} (${TOOLS.length} tools).`);
